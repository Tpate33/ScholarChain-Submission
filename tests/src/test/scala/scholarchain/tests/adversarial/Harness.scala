/**
 * Independent harness of the adversarial suites (owner: test-engineer). It drives the REAL Hadoop
 * pipeline (`scholarchain.hadoop.pipeline.Pipeline`, LocalJobRunner) from the hadoop main classes
 * only; nothing from modules/hadoop's test sources is used. Every input is a fixture under
 * `tests/src/test/resources/adversarial/` or generated by test code in the tests tree, copied or
 * written into `tests/target/test-work/<name>/`; every output stays under that directory.
 */
object Harness {

  lazy val repoRoot: JPath = {
    var dir = new File(".").getCanonicalFile.toPath
    while (
      dir != null && !(Files.isRegularFile(dir.resolve("build.sbt")) &&
        Files.isDirectory(dir.resolve("tests/src/test")))
    ) dir = dir.getParent
    require(dir != null, "repository root (build.sbt + tests/src/test) not found")
    dir
  }

  val ResourceRoot: String = "tests/src/test/resources/adversarial"

  def resource(rel: String): JPath = repoRoot.resolve(ResourceRoot).resolve(rel)

  def readResource(rel: String): String =
    new String(Files.readAllBytes(resource(rel)), StandardCharsets.UTF_8)

  /** A fresh, empty directory under tests/target/test-work. */
  def workDir(name: String): JPath = {
    val d = repoRoot.resolve("tests/target/test-work").resolve(name)
    if (Files.exists(d)) FileUtil.fullyDelete(d.toFile)
    Files.createDirectories(d)
    d
  }

  /** Copies a committed fixture into the work directory (inputs are read from target only). */
  def stage(work: JPath, rel: String, as: String): JPath = {
    val dst = work.resolve("input").resolve(as)
    Files.createDirectories(dst.getParent)
    Files.copy(resource(rel), dst, StandardCopyOption.REPLACE_EXISTING)
    dst
  }

  /** Writes generated fixture text into the work directory. */
  def writeInput(work: JPath, as: String, content: String): JPath = {
    val dst = work.resolve("input").resolve(as)
    Files.createDirectories(dst.getParent)
    Files.write(dst, content.getBytes(StandardCharsets.UTF_8))
    dst
  }

  def hpath(p: JPath): Path = new Path(p.toUri)

  /** Hadoop configuration for the local job runner; `splitMax` bounds DBLP/JSONL split size. */
  def localConf(work: JPath, splitMax: Option[Long]): Configuration = {
    val c = new Configuration()
    c.set("fs.defaultFS", "file:///")
    c.set("mapreduce.framework.name", "local")
    c.set("hadoop.tmp.dir", work.resolve("hadoop-tmp").toString)
    splitMax.foreach(s => c.setLong(FileInputFormat.SPLIT_MAXSIZE, s))
    c
  }

  /** Snapshot tokens of datasets/dataset-manifest.yaml (copied, not imported). */
  val snapshots: Vector[SnapshotRef] = Vector(
    SnapshotRef(SourceType.Dblp, "dblp-2026-10-03"),
    SnapshotRef(SourceType.OpenAlex, "openalex-2026-10-14"),
    SnapshotRef(SourceType.Crossref, "crossref-public-data-file-2026-03"),
    SnapshotRef(SourceType.Orcid, "ORCID_2025_10")
  )

  /** Normalize + teams + exact-ids parameters (test values only). */
  def baseParams(teamMaxSize: Int = 100): Map[String, String] = Map(
    JobParams.DblpRecordTypes -> "article,inproceedings",
    JobParams.DblpYearRange -> "*",
    JobParams.DblpVenues -> "*",
    JobParams.DblpEncoding -> "UTF-8",
    JobParams.DblpMaxRecordBytes -> "1048576",
    JobParams.OrcidMaxRecordBytes -> "1048576",
    JobParams.RejectMaxExcerptChars -> "4000",
    JobParams.TeamSources -> "dblp",
    JobParams.TeamMaxSize -> teamMaxSize.toString,
    JobParams.ReducersNormalize -> "3",
    JobParams.ReducersExactIds -> "2",
    JobParams.ReducersTeams -> "2",
    JobParams.CodecIntermediate -> "org.apache.hadoop.io.compress.DefaultCodec",
    JobParams.CodecOutput -> "org.apache.hadoop.io.compress.GzipCodec"
  )

  /** Blocking with the REAL entity-resolution key source. */
  def blockingParams(maxBlockSize: Int, policy: String): Map[String, String] = Map(
    JobParams.BlockingKeySourceClass ->
      classOf[scholarchain.hadoop.jobs.EntityResolutionKeySource].getName,
    JobParams.BlockingKeySourceVersion -> EntityResolution.blockingKeysVersion,
    JobParams.BlockingMaxBlockSize -> maxBlockSize.toString,
    JobParams.BlockingOversizePolicyKey -> policy,
    JobParams.ReducersBlocking -> "2"
  )

  val candidateParams: Map[String, String] = Map(
    JobParams.CandidatesFeatureVersion -> EntityResolution.featuresVersion,
    JobParams.ReducersCandidates -> "2"
  )

  def manifest(params: Map[String, String], attempt: Int = 1): RunManifest =
    RunManifest(
      schemaVersion = SchemaVersions.RunManifest,
      stage = "hadoop.pipeline",
      codeVersion = "0123456789abcdef0123456789abcdef01234567",
      configDigest = "b" * 64,
      inputSnapshots = snapshots,
      parameters = SortedMap.from(params),
      attempt = attempt
    )

  def runIdOf(m: RunManifest): String =
    RunId.of(m).fold(e => throw new IllegalStateException(e.message), identity)

  def inputs(
      dblp: Vector[JPath],
      openAlexWorks: Vector[JPath] = Vector.empty,
      openAlexAuthors: Vector[JPath] = Vector.empty,
      openAlexInstitutions: Vector[JPath] = Vector.empty,
      crossrefWorks: Vector[JPath] = Vector.empty,
      orcid: Vector[JPath] = Vector.empty
  ): PipelineInputs =
    PipelineInputs(
      dblp.map(hpath),
      openAlexWorks.map(hpath),
      openAlexAuthors.map(hpath),
      openAlexInstitutions.map(hpath),
      crossrefWorks.map(hpath),
      orcid.map(hpath)
    )

  /** Runs the pipeline; a refused or failed run is returned as Left with the driver's messages. */
  def tryRun(
      conf: Configuration,
      m: RunManifest,
      root: JPath,
      in: PipelineInputs,
      stages: Vector[Stage]
  ): Either[Vector[String], Vector[StageReport]] =
    Pipeline.run(conf, m, hpath(root), in, stages)

  def run(
      conf: Configuration,
      m: RunManifest,
      root: JPath,
      in: PipelineInputs,
      stages: Vector[Stage]
  ): Vector[StageReport] =
    tryRun(conf, m, root, in, stages).fold(
      errors => throw new AssertionError("pipeline failed:\n" + errors.mkString("\n")),
      identity
    )

  def runRoot(root: JPath, m: RunManifest): Path =
    RunLayout.of(hpath(root), m, runIdOf(m)).fold(e => throw new IllegalStateException(e), _.root)

  def lines(conf: Configuration, dir: Path): Vector[String] =
    Pipeline.readLines(conf, dir.getFileSystem(conf), dir)

  /** Streams every line of every part file of `dir` (for outputs too large to hold as strings). */
  def foreachLine(conf: Configuration, dir: Path)(f: String => Unit): Long = {
    val fs = dir.getFileSystem(conf)
    if (!fs.exists(dir)) 0L
    else {
      val factory = new CompressionCodecFactory(conf)
      var n = 0L
      fs.listStatus(dir)
        .toVector
        .filter(s => s.isFile && s.getPath.getName.startsWith("part-"))
        .sortBy(_.getPath.getName)
        .foreach { s =>
          val codec = factory.getCodec(s.getPath)
          val raw = fs.open(s.getPath)
          val in = if (codec == null) raw else codec.createInputStream(raw)
          val reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8))
          try {
            var line = reader.readLine()
            while (line != null) {
              f(line)
              n += 1
              line = reader.readLine()
            }
          } finally reader.close()
        }
      n
    }
  }

  def rejects(conf: Configuration, dir: Path): Vector[RejectRecord] =
    lines(conf, dir).map(RejectRecord.fromJson)

  def decodeAll[T](ls: Vector[String])(using RecordContract[T]): Vector[T] =
    ls.map(l =>
      Json
        .decode[T](l)
        .fold(e => throw new AssertionError(s"does not decode: $l: ${e.map(_.message)}"), identity)
    )

  def cnt(m: SortedMap[String, Long], k: String): Long = m.getOrElse(k, 0L)

  def stageOf(rs: Vector[StageReport], name: String): StageReport =
    rs.find(_.stage == name).getOrElse(throw new AssertionError(s"no $name stage report"))

  def printReport(tag: String, rs: Vector[StageReport]): Unit =
    rs.foreach { r =>
      println(s"[$tag] stage=${r.stage} status=${r.status}")
      r.counters.foreach { case (k, v) => println(s"[$tag]   counter $k=$v") }
      r.stats.foreach { case (k, s) => println(s"[$tag]   stat $k=${s.value} id=${s.id}") }
    }

  /** Every directory under `run` (recursive) holding part files, keyed by relative path. */
  def outputDirs(conf: Configuration, run: Path): Vector[(String, Path)] = {
    val fs = run.getFileSystem(conf)
    def walk(p: Path): Vector[Path] =
      fs.listStatus(p).toVector.filter(_.isDirectory).flatMap(s => s.getPath +: walk(s.getPath))
    walk(run)
      .filter(d => fs.listStatus(d).exists(s => s.isFile && s.getPath.getName.startsWith("part-")))
      .map(d => d.toString.stripPrefix(run.toString) -> d)
  }

  def snapshot(conf: Configuration, run: Path): SortedMap[String, Vector[String]] =
    SortedMap.from(outputDirs(conf, run).map { case (rel, d) => rel -> lines(conf, d) })

  /** Documented reject reasons (job-contracts.md, "Reject reasons"). */
  val RejectReasons: Set[String] = Set(
    "malformed-xml",
    "malformed-json",
    "unterminated-record",
    "missing-field",
    "malformed-field",
    "malformed-identifier",
    "schema-failure",
    "invalid-blocking-key",
    "missing-key",
    "unresolved-member",
    "conflict",
    "oversize-team",
    "oversize-block"
  )

  val SchemaFailureReasons: Set[String] = Set(
    "malformed-xml",
    "malformed-json",
    "unterminated-record",
    "missing-field",
    "malformed-field",
    "malformed-identifier",
    "schema-failure",
    "invalid-blocking-key"
  )

  val MissingKeyReasons: Set[String] = Set("missing-key", "unresolved-member")

  /**
   * Cross-module contract check: every curated line of a run decodes with the strict core decoder
   * (`Json.decode`) into its contract, carries this run's ID in its provenance, and every reject
   * line is a well-formed `scholarchain.hadoop.reject.v1` record of this run. Returns the number of
   * curated lines checked per directory.
   */
  def checkContracts(conf: Configuration, run: Path, runId: String): SortedMap[String, Int] = {
    def check[T](rel: String, d: Path)(using c: RecordContract[T]): Int = {
      val ls = lines(conf, d)
      decodeAll[T](ls).foreach { t =>
        val prov = c.provenanceOf(t)
        if (prov.runId != runId)
          throw new AssertionError(s"$rel: provenance runId ${prov.runId} != $runId")
      }
      ls.size
    }
    val counts = outputDirs(conf, run).map { case (rel, d) =>
      val n = rel match {
        case r if r.endsWith("/normalize/works") => check[WorkRecord](r, d)
        case r if r.endsWith("/normalize/mentions") => check[AuthorMention](r, d)
        case r if r.endsWith("/normalize/profiles") => check[SourceAuthorProfile](r, d)
        case r if r.endsWith("/normalize/venues") => check[Venue](r, d)
        case r if r.endsWith("/normalize/institutions") => check[Institution](r, d)
        case r if r.endsWith("/normalize/topics") => check[Topic](r, d)
        case r if r.endsWith("/exact-ids/links") => check[IdentityLink](r, d)
        case r if r.endsWith("/teams/teams") => check[PublicationTeam](r, d)
        case r if r.endsWith("/teams/pairs") => check[CoauthorPairCandidate](r, d)
        case r if r.contains("/blocks/") => check[CandidateBlock](r, d)
        case r
            if r.contains("/candidates/final/") && !r.endsWith("/rejects") &&
              !r.endsWith("/stats") =>
          check[MatchCandidate](r, d)
        case r if r.contains("/candidates/pairs/pairs") => check[MatchCandidate](r, d)
        case r if r.endsWith("/rejects") =>
          val rs = rejects(conf, d)
          rs.foreach { x =>
            if (
              x.schemaVersion != RejectRecord.SchemaVersion || x.runId != runId ||
              !RejectReasons(x.reason) || !Set("rejected", "flagged")(x.disposition) ||
              !x.rejectId.startsWith("reject:") || x.locator.isEmpty
            ) throw new AssertionError(s"$rel: malformed reject record $x")
          }
          rs.size
        case _ => -1 // hadoop-internal intermediates (spill, members, joined, stats)
      }
      rel -> n
    }
    SortedMap.from(counts.filter(_._2 >= 0))
  }

  /** Bytes of a fixture file (for locator offsets). */
  def bytes(p: JPath): Array[Byte] = Files.readAllBytes(p)

  /** Byte offset of the first occurrence of `needle` in `hay`, or -1. */
  def indexOf(hay: Array[Byte], needle: String, from: Int = 0): Int = {
    val n = needle.getBytes(StandardCharsets.UTF_8)
    var i = from
    var found = -1
    while (found < 0 && i <= hay.length - n.length) {
      var j = 0
      while (j < n.length && hay(i + j) == n(j)) j += 1
      if (j == n.length) found = i
      i += 1
    }
    found
  }

  def fileExists(conf: Configuration, p: Path): Boolean = FileSystem.getLocal(conf).exists(p)
}
